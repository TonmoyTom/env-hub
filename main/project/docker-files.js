'use strict';

const fs = require('fs');
const path = require('path');
const { portableCompose, portableComposeYaml, portableDockerfile, portableEnvText } = require('./portable-compose');
const { phpDockerfile, NGINX_CONF } = require('./scaffold');

// "Generate Docker files" (Settings tab): writes the Docker setup of a project into its own folder,
// so the folder can be started without ProjectDockHub (docker compose up -d --build), on this computer or a server.
// A project that was brought in (an existing folder) has no such files until this button is pressed.

const IGNORE_COMMON = ['.git', '.gitignore', '.env', '.env.*', '*.bak', '*.log', '.idea', '.vscode', 'docker-compose.yml'];
const IGNORE_BY_KIND = {
  laravel: [
    'node_modules', 'vendor',
    'storage/logs/*', 'storage/framework/cache/*', 'storage/framework/sessions/*', 'storage/framework/views/*',
    'bootstrap/cache/*.php', 'public/hot', 'public/storage',
  ],
  node: ['node_modules', '.next', '.nuxt', '.output', 'dist', 'build', 'coverage'],
  docker: ['node_modules', '__pycache__', '*.pyc', '.venv', 'venv'],
};

function kindOf(spec) {
  if (spec.stack === 'laravel') return 'laravel';
  return spec.stack === 'docker' ? 'docker' : 'node';
}

// What Docker leaves out when it builds an image: secrets, packages that are installed again, caches.
function dockerignoreText(spec) {
  return [
    '# Generated by ProjectDockHub. These files are not copied into a Docker image.',
    ...IGNORE_COMMON,
    ...IGNORE_BY_KIND[kindOf(spec)],
  ].join('\n') + '\n';
}

// Every file of the setup, as [{ path (relative, with /), content }]. Pure.
//   passwords = { app, root }  the database passwords the project uses now
//   hasEnv    = the folder already has its own .env (it is never changed; the values go to .env.docker)
function dockerFilesFor(spec, { app = '', root = '' } = {}, hasEnv = false) {
  const files = [];
  if (spec.stack === 'laravel') {
    files.push({ path: 'docker/php/Dockerfile', content: phpDockerfile(spec.phpVersion, spec.phpExtensions || []) });
    files.push({ path: 'docker/nginx/default.conf', content: NGINX_CONF });
  } else {
    files.push({ path: 'Dockerfile', content: portableDockerfile(spec) });
  }
  files.push({ path: 'docker-compose.yml', content: portableComposeYaml(spec) });
  files.push({ path: '.dockerignore', content: dockerignoreText(spec) });
  files.push({
    path: hasEnv ? '.env.docker' : '.env',
    content: portableEnvText({ ...spec, dbPassword: app || root, rootPassword: root }),
  });
  return files;
}

// The command that starts the folder without ProjectDockHub.
function startCommand(hasEnv) {
  return hasEnv ? 'docker compose --env-file .env.docker up -d --build' : 'docker compose up -d --build';
}

function assertFolder(spec) {
  if (!spec.folder || !fs.existsSync(spec.folder) || !fs.statSync(spec.folder).isDirectory()) {
    throw new Error('The project folder was not found.');
  }
}

// True when the folder has an .env that is the project's own. An .env that an earlier Generate wrote
// (same text as now) is not: it stays the place for the values.
function hasOwnEnv(spec, passwords) {
  const file = path.join(spec.folder, '.env');
  if (!fs.existsSync(file)) return false;
  const ours = dockerFilesFor(spec, passwords, false).find((f) => f.path === '.env').content;
  return fs.readFileSync(file, 'utf8') !== ours;
}

// What Generate would do, without writing: the services, and for every file 'new', 'same' or 'replace'.
function previewDockerFiles(spec, passwords) {
  assertFolder(spec);
  const hasEnv = hasOwnEnv(spec, passwords);
  const files = dockerFilesFor(spec, passwords, hasEnv).map((file) => {
    const target = path.join(spec.folder, file.path);
    let status = 'new';
    if (fs.existsSync(target)) status = fs.readFileSync(target, 'utf8') === file.content ? 'same' : 'replace';
    return { path: file.path, status };
  });
  return {
    folder: spec.folder,
    services: Object.keys(portableCompose(spec).services),
    files,
    command: startCommand(hasEnv),
  };
}

// Writes the files. A file that exists with other content is kept as <name>.bak first.
// The project's own .env is never touched. Returns { folder, written, same, backups, command }.
function generateDockerFiles(spec, passwords) {
  assertFolder(spec);
  const hasEnv = hasOwnEnv(spec, passwords);
  const written = [];
  const same = [];
  const backups = [];
  for (const file of dockerFilesFor(spec, passwords, hasEnv)) {
    const target = path.join(spec.folder, file.path);
    if (fs.existsSync(target)) {
      if (fs.readFileSync(target, 'utf8') === file.content) {
        same.push(file.path);
        continue;
      }
      fs.copyFileSync(target, `${target}.bak`);
      backups.push(`${file.path}.bak`);
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    // The env file holds passwords: readable by the owner only (where the system supports it).
    fs.writeFileSync(target, file.content, file.path.startsWith('.env') ? { mode: 0o600 } : undefined);
    written.push(file.path);
  }
  return { folder: spec.folder, written, same, backups, command: startCommand(hasEnv) };
}

module.exports = { dockerFilesFor, dockerignoreText, previewDockerFiles, generateDockerFiles, startCommand };
